// Ledgers: the case seen from the outside. Generated from the model so they
// cannot drift from the content that actually ships.

import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { people, organisations, places, timelines } from './model/world.mjs'

const ACT_NAMES = { 1: 'I · Anomaly', 2: 'II · Pattern', 3: 'III · Second story', 4: 'IV · Recontextualisation', 5: 'V · Hidden truth', 6: 'VI · Reconstruction' }
const esc = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')

export function writeLedgers({ nodes, artifacts, ACT_OF, ORDER, ROOT }) {
  const dir = join(ROOT, 'docs', 'case')
  mkdirSync(dir, { recursive: true })
  const out = (name, text) => writeFileSync(join(dir, name), text.trimEnd() + '\n')
  const stamp = '_Generated by `case/compile.mjs` from `case/model`. Do not edit by hand._\n'
  const nodeBy = Object.fromEntries(nodes.map(n => [n.code, n]))

  // dependency ledger
  {
    const rows = nodes.map(n => `| ${n.code} | ${ACT_OF[n.code]} | ${esc(n.title)} | ${esc(n.question)} | ${(n.uses ?? []).join(', ') || '—'} | ${n.recontext ? esc(n.recontext.what) : '—'} | ${n.mech} |`)
    out('DEPENDENCY_LEDGER.md', `# Content dependency ledger\n\n${stamp}\nWhat each lead asks, what earlier findings it needs, what belief it overturns.\n\n| Lead | Act | Title | Claim asked | Depends on | Recontextualises | Mechanic |\n|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`)
  }

  // answer key
  {
    const rows = nodes.map(n => `| ${n.code} | ${esc(n.answer)} | ${esc(n.alts.join(' · '))} | ${esc(n.solution)} |`)
    out('ANSWER_KEY.md', `# Answer key (spoilers)\n\n${stamp}\n| Lead | Answer | Also accepted | Solution |\n|---|---|---|---|\n${rows.join('\n')}\n`)
  }

  // evidence ledger
  {
    const rows = artifacts.map(a => `| ${a.id} | ${a.node} | ${a.kind} | ${esc(a.title)} | ${esc(a.custodian)} | ${a.reliability} | ${esc(a.proves.join('; '))} | ${esc(a.doesNotProve.join('; '))} |`)
    out('EVIDENCE_LEDGER.md', `# Evidence ledger\n\n${stamp}\nEvery exhibit with its provenance, what it establishes, and what it does not.\n\n| Exhibit | Lead | Kind | Title | Custodian | Reliability | Proves | Does not prove |\n|---|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`)
  }

  // evidence graph
  {
    const lines = ['flowchart LR']
    for (const a of artifacts) lines.push(`  ${a.id.replace(/-/g, '_')}["${a.id}<br/>${a.title.replace(/"/g, "'")}"]`)
    for (const a of artifacts) for (const r of a.relates ?? []) {
      const arrow = r.kind === 'contradicts' ? '-. contradicts .->' : r.kind === 'corroborates' ? '-- corroborates -->' : `-- ${r.kind} -->`
      lines.push(`  ${a.id.replace(/-/g, '_')} ${arrow} ${r.to.replace(/-/g, '_')}`)
    }
    const edges = artifacts.reduce((n, a) => n + (a.relates?.length ?? 0), 0)
    const byKind = {}
    for (const a of artifacts) for (const r of a.relates ?? []) byKind[r.kind] = (byKind[r.kind] ?? 0) + 1
    out('EVIDENCE_GRAPH.md', `# Evidence graph\n\n${stamp}\n${artifacts.length} nodes, ${edges} edges (${Object.entries(byKind).map(([k, v]) => `${v} ${k}`).join(', ')}).\n\n\`\`\`mermaid\n${lines.join('\n')}\n\`\`\`\n`)
  }

  // twists
  {
    const recon = nodes.filter(n => n.recontext).map(n => `| ${n.code} | ${esc(n.recontext.what)} | ${esc(n.recontext.from)} | ${esc(n.recontext.to)} |`)
    const revel = nodes.filter(n => n.revelation).map(n => `| ${n.code} | ${esc(n.revelation)} |`)
    const herr = nodes.filter(n => n.redHerring).map(n => `| ${n.redHerring.id} | ${n.code} | ${esc(n.redHerring.theory)} | ${esc(n.redHerring.refutedBy)} |`)
    out('TWIST_LEDGER.md', `# Twist ledger\n\n${stamp}\n## Major revelations\n\n| Lead | Revelation |\n|---|---|\n${revel.join('\n')}\n\n## Recontextualisation matrix\n\n| Lead | What changes | Before | After |\n|---|---|---|---|\n${recon.join('\n')}\n\n## Red herrings\n\n| Id | Lead | Theory | Refuted by |\n|---|---|---|---|\n${herr.join('\n')}\n`)
  }

  // characters
  {
    const blocks = people.map(p => `## ${p.name}\n\n- **1994:** ${p.role1994}\n- **2024:** ${p.role2024}\n- **Wants:** ${p.wants}\n- **Fears:** ${p.fears}\n- **Secrets:** ${p.secrets.join('; ') || '—'}\n- **Lies told:** ${p.lies.join('; ') || '—'}\n- **Knows about:** ${p.knowsAbout}\n- **Appears in:** ${p.appears.join(', ')}\n`)
    const orgs = organisations.map(o => `- **${o.name}** (${o.years}): ${o.note}`)
    const pl = places.map(p => `- **${p.name}**: ${p.note}`)
    out('CHARACTER_LEDGER.md', `# Character, organisation and place ledger\n\n${stamp}\n${blocks.join('\n')}\n## Organisations\n\n${orgs.join('\n')}\n\n## Places\n\n${pl.join('\n')}\n`)
  }

  // timelines
  {
    const t = list => list.map(([when, what]) => `| ${esc(when)} | ${esc(what)} |`).join('\n')
    out('TIMELINES.md', `# Timelines\n\n${stamp}\n## What the bulletin says\n\n| When | What |\n|---|---|\n${t(timelines.official)}\n\n## False theories the evidence invites\n\n| When | What |\n|---|---|\n${t(timelines.false)}\n\n## What happened\n\n| When | What |\n|---|---|\n${t(timelines.true)}\n`)
  }

  // coverage
  {
    const total = nodes.length
    const dep = nodes.filter(n => (n.uses ?? []).length).length
    const comb = nodes.filter(n => (n.uses ?? []).length >= 2).length
    const rec = nodes.filter(n => n.recontext).length
    const rev = nodes.filter(n => n.revelation).length
    const mechs = {}
    for (const n of nodes) mechs[n.mech] = (mechs[n.mech] ?? 0) + 1
    const perAct = Object.entries(ACT_NAMES).map(([a, name]) => {
      const list = nodes.filter(n => ACT_OF[n.code] === Number(a))
      return `| ${name} | ${list.length} | ${list.filter(n => (n.uses ?? []).length).length} | ${list.filter(n => n.recontext).length} | ${artifacts.filter(x => ACT_OF[x.node] === Number(a)).length} |`
    })
    const kinds = {}
    for (const a of artifacts) kinds[a.kind] = (kinds[a.kind] ?? 0) + 1
    const pct = x => `${Math.round((x / total) * 100)}%`
    out('COVERAGE.md', `# Coverage\n\n${stamp}\n| Measure | Value | Target |\n|---|---|---|\n| Leads | ${total} | 47 |\n| Depend on earlier findings | ${dep} (${pct(dep)}) | ≥ 75% |\n| Combine two or more earlier findings | ${comb} (${pct(comb)}) | ≥ 50% |\n| Recontextualisations | ${rec} | ≥ 10 |\n| Major revelations | ${rev} | ≥ 5 |\n| Exhibits | ${artifacts.length} | — |\n\n## Per act\n\n| Act | Leads | Dependent | Recontextualise | Exhibits |\n|---|---|---|---|---|\n${perAct.join('\n')}\n\n## Mechanics used\n\n${Object.entries(mechs).sort((a, b) => b[1] - a[1]).map(([k, v]) => `- ${k}: ${v}`).join('\n')}\n\n## Exhibit kinds\n\n${Object.entries(kinds).map(([k, v]) => `- ${k}: ${v}`).join('\n')}\n`)
  }
  void ORDER
  void nodeBy
  console.log(`docs: 8 ledgers in docs/case/`)
}
